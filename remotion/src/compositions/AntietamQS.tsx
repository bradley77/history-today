export default function AntietamQS() {
  let offset = 0;
  const froms = slidesWithFrames.map((s) => {
    const from = offset;
    offset += s.durationFrames;
    return from;
  });
  // slide 4 ends (audio + 0.4s pad) exactly where the end card begins --
  // `offset` here is the running total after the last story slide, i.e. the
  // same accumulator every other Sequence's `from` is derived from, so
  // there is no gap or overlap by construction.
  const ctaFrom = offset;

  return (
    <AbsoluteFill style={{ backgroundColor: '#000' }}>
      <style>{`@import url('${OSWALD_URL}');`}</style>

      {/* One-off music swap for this video only -- LincolnFortStevens's
          bed, not the standing Civil War Quick Strikes default
          (Gettysburg-Day1-music.mp3), which is unchanged everywhere else. */}
      <Audio src={staticFile('audio/LincolnFortStevens-music.mp3')} volume={0.15} loop />

      {slidesWithFrames.map((slide, i) => (
        <Sequence key={slide.id} from={froms[i]} durationInFrames={slide.durationFrames} layout="none">
          <ContentSlide slide={slide} isFirst={i === 0} />
        </Sequence>
      ))}

      <Sequence from={ctaFrom} durationInFrames={CTA_FRAMES} layout="none">
        <EndCard />
      </Sequence>
    </AbsoluteFill>
  );
}
