//
// Locked decisions from the build brief:
//   - No fades anywhere: true cold open at frame 0 (handled by SlidePanel's
//     isFirst prop), hard cut on every other slide, no fade to black at the
//     end (end card renders at constant opacity 1 -- see EndCard below).
//   - Per-slide audio only (one <Audio> per Sequence) -- no continuous track.
//   - Three-layer text system on slides 1-4:
//       1. ContextTag (`label`) -- short persistent top-left tag.
//       2. CaptionOverlay (`captionLines`) -- the locked VO script,
//          verbatim, split into per-clause cues that word-time against
//          each slide's own audioDurationFrames.
//       3. GoldLowerThird (`overlayText`) -- a short ADDITIVE line (not a
//          repeat of the caption), giving silent viewers context the VO
//          doesn't state out loud. Omitted on slide 1 (too short for two
//          text blocks).
//     STACKING ORDER (swapped from the shared SlidePanel default): CaptionOverlay
//     is bottom-anchored, hugging SAFE_ZONE_BOTTOM_Y exactly, and the headline
//     is repositioned every frame to sit just above whichever caption cue is
//     currently active -- the reverse of SlidePanel's baked-in wiring (headline
//     fixed at the bottom, caption computed to avoid it). SlidePanel's own
//     prop surface has no way to express "headline reacts to caption," so
//     slides 1-4 use a local ContentSlide component below instead of SlidePanel,
//     composed from the same shared building blocks (KenBurnsImage, Vignette,
//     ContextTag, CaptionOverlay) plus a local HeadlineBox in place of
//     GoldLowerThird (also local -- see HeadlineBox for why: it needed a
//     vertical-padding trim GoldLowerThird's props don't expose, on top of the
//     positioning reversal). The reversal itself uses HeadlineBox's
//     bottomOffset prop (mirrors GoldLowerThird's own -- public API either way,
//     no shared-file edits) to push the headline up by however tall the active
//     caption cue's box currently is -- see ContentSlide below for the exact
//     math, which duplicates CaptionOverlay's own internal (non-exported)
//     line-wrap/height formulas since there's no way to read that back out of
//     the locked component otherwise.
//   - Pan-Fill scale/pan math: pan mode holds scale FIXED at baseScale
//     (= CANVAS_HEIGHT / sourceHeight, the zoom that fills the canvas
//     height) and only animates translateX within the image's own
//     overflow past 1080px at that scale (panRoomPx). The image can
//     therefore never reveal its edge no matter how far it pans, which is
//     exactly the invariant the legacy manual-motion rule (scale >=1.06 for
//     pan >20px, >=1.08 for >30px) protected against by hand -- Pan-Fill
//     satisfies it structurally, not via a tuned scale value.

