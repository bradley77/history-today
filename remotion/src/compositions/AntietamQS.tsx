// five-fact Antietam PDF. Follow for more.") is wired through EndCardCTA's
// own `audio` prop, so the whole card is voiced, not silent -- a deliberate
// departure from the other QuickStrikes' Max Alignment rule (VO limited to
// just the comment-trigger line) per this brief. "FOLLOW FOR MORE" below
// the card matches the established silent-badge wording used elsewhere
// (never "Follow Echo and Chronicle"), but is rendered at constant opacity
// here rather than the usual delayed reveal, and the whole EndCard skips
// the standard HARD_CUT_FRAMES entrance fade every other QuickStrike end
// card uses -- both per this brief's "no fade in/out on the end card" rule.
// ---------------------------------------------------------------------------
const CTA_SUBLINE = 'FOR THE 5-FACT ANTIETAM PDF';
const CTA_DURATION_S = CTA_AUDIO_S + PAD_S;
const CTA_FRAMES = Math.round(CTA_DURATION_S * FPS);
