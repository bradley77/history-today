// ---------------------------------------------------------------------------
// Caption-height math, duplicated from QuickStrikeShared's internal (non-
// exported) CaptionOverlay helpers -- estimateWrappedLineCount,
// captionBlockHeight, and the caption's own CAPTION_* sizing constants.
// QuickStrikeShared.tsx is locked/consume-only (same rule IaDrangValleyQS.tsx
// follows for its own local duplicate of BOTTOM_SAFE_BUFFER), and none of this
// math is exported, so it's reproduced here verbatim rather than imported.
// Needed because the stacking swap requires GoldLowerThird to react to the
// ACTIVE caption cue's box height every frame, and CaptionOverlay has no way
// to report that back out.
// ---------------------------------------------------------------------------
const CAPTION_MAX_WIDTH = 900;
const CAPTION_H_PADDING = 20;
const CAPTION_V_PADDING = 10;
const CAPTION_FONT_SIZE = 38;
const CAPTION_LINE_HEIGHT = 1.3;
// Mirrors QuickStrikeShared's own (non-exported) BOTTOM_SAFE_BUFFER.
const BOTTOM_SAFE_BUFFER = 20;
// Visual gap kept between GoldLowerThird's box bottom and CaptionOverlay's
// box top -- same spirit as (not a literal copy of) CAPTION_HEADLINE_GAP,
// which measured from the headline's TEXT rather than its outer box edge
// because the caption used to be the one doing the avoiding; here GoldLowerThird
// is positioned via its own box-edge-anchored `bottomOffset`, so the gap is
// measured edge-to-edge instead.
const HEADLINE_CAPTION_GAP = 20;
// Passed as CaptionOverlay's `top` prop on every content slide. CaptionOverlay
// resolves its position as `Math.min(top, ceiling - height)` -- an
// unreachably large `top` forces it to always take the `ceiling - height`
// branch, i.e. hug SAFE_ZONE_BOTTOM_Y exactly and grow upward, regardless of
// cue length. No `overlayText` is passed to CaptionOverlay on these slides
// (that's the other half of the swap), so `ceiling` here is always the plain
// safe-zone line with no headline-avoidance math applied.
const CAPTION_HUG_BOTTOM_TOP = 999999;

// Verbatim copy of CaptionOverlay's internal estimateWrappedLineCount --
// replays the browser's own greedy line-wrap against the caption box's real
// font/width so the height computed below matches what CaptionOverlay itself
// will actually render.
function estimateWrappedLineCount(text: string, maxTextWidth: number, fontSize: number): number {
  if (typeof document === 'undefined') return 1;
  const ctx = document.createElement('canvas').getContext('2d');
  if (!ctx) return 1;
  ctx.font = `700 ${fontSize}px 'Oswald', Impact, 'Arial Black', sans-serif`;

  const words = text.split(/\s+/).filter(Boolean);
  let lineCount = 1;
  let lineWidth = 0;
  for (const word of words) {
    const wordWidth = ctx.measureText(`${word} `).width;
    if (lineWidth > 0 && lineWidth + wordWidth > maxTextWidth) {
      lineCount += 1;
      lineWidth = wordWidth;
    } else {
      lineWidth += wordWidth;
    }
  }
  return lineCount;
}

// Verbatim copy of CaptionOverlay's internal captionBlockHeight.
function captionBlockHeight(lineCount: number, fontSize: number): number {
  return lineCount * fontSize * CAPTION_LINE_HEIGHT + CAPTION_V_PADDING * 2;
}

// Verbatim copy of CaptionOverlay's internal cue-selection logic (word-count-
// proportional timing across audioDurationFrames) -- needed here so
// ContentSlide can know which cue CaptionOverlay itself will be showing at
// the current frame, to size the headline gap against the right cue.
function getActiveCaptionLine(lines: string[], frame: number, audioDurationFrames: number): string {
  const wordCounts = lines.map((line) => line.split(/\s+/).filter(Boolean).length);
  const totalWords = wordCounts.reduce((a, b) => a + b, 0);
  let wordsSoFar = 0;
  let startFrame = 0;
  for (const [i, line] of lines.entries()) {
    wordsSoFar += wordCounts[i];
    const endFrame = Math.round((wordsSoFar / totalWords) * audioDurationFrames);
    if (frame >= startFrame && frame < endFrame) return line;
    startFrame = endFrame;
  }
  return lines[lines.length - 1];
}

// ---------------------------------------------------------------------------
// HeadlineBox -- local replica of GoldLowerThird with its vertical padding
// trimmed ~25% (24px -> 18px). GoldLowerThird has no padding-override prop,
// and QuickStrikeShared.tsx is locked/consume-only, so this reproduces its
// exact visual design (same rule/box/text styling, same useGoldOverlay
// reveal timing, same bottomOffset-driven bottom-anchor positioning --
// copied verbatim from GoldLowerThird's own source) with ONLY the inner
// box's vertical padding changed. Horizontal padding (40px), font size/
// weight/family, text color, rule color/thickness, and box background
// color/opacity are all untouched, copied as-is. This does NOT change the
// stacking math from the previous fix -- bottomOffset still anchors the
// box's OUTER bottom edge (the padding trim only shrinks the box from
// there, it doesn't move the anchor itself), so ContentSlide's
// headlineBottomOffset computation below needs no changes. Also mirrors
// GoldLowerThird's own (now-additive) safeZoneBottomY prop, defaulting to
// the same module constant, so this local replica stays in sync with the
// shared component's API surface.
// ---------------------------------------------------------------------------
const HEADLINE_H_PADDING = 40; // unchanged, copied from GoldLowerThird's own '24px 40px'
const HEADLINE_V_PADDING = 18; // was 24px -- 25% reduction, per this fix

function HeadlineBox({
  text,
  frame,
  bottomOffset = 0,
  safeZoneBottomY = SAFE_ZONE_BOTTOM_Y,
}: {
  text: string;
  frame: number;
  bottomOffset?: number;
  safeZoneBottomY?: number;
}) {
  const { ruleWidth, textOpacity } = useGoldOverlay(frame);

  return (
    <AbsoluteFill
      style={{
        justifyContent: 'flex-end',
        alignItems: 'center',
        padding: `0 48px ${CANVAS_HEIGHT - safeZoneBottomY + BOTTOM_SAFE_BUFFER - bottomOffset}px`,
        pointerEvents: 'none',
      }}
    >
      <div style={{ width: '100%' }}>
        <div
          style={{
            height: 3,
            width: `${ruleWidth}%`,
            backgroundColor: GOLD,
            marginBottom: 16,
            marginLeft: 'auto',
            marginRight: 'auto',
          }}
        />
        <div
          style={{
            backgroundColor: 'rgba(0,0,0,0.60)',
            padding: `${HEADLINE_V_PADDING}px ${HEADLINE_H_PADDING}px`,
            textAlign: 'center',
          }}
        >
          <p
            style={{
              fontSize: 52,
              fontWeight: 700,
              color: '#F5F0E8',
              margin: 0,
              lineHeight: 1.25,
              textShadow: '0 2px 14px rgba(0,0,0,0.95)',
              fontFamily: "'Oswald', Impact, 'Arial Black', sans-serif",
              letterSpacing: '0.01em',
              opacity: textOpacity,
            }}
          >
            {text}
          </p>
        </div>
        <div
          style={{
            height: 3,
            width: `${ruleWidth}%`,
            backgroundColor: GOLD,
            marginTop: 16,
            marginLeft: 'auto',
            marginRight: 'auto',
          }}
        />
      </div>
    </AbsoluteFill>
  );
}

// ---------------------------------------------------------------------------
// ContentSlide -- replaces SlidePanel for slides 1-4 so the caption/headline
// stacking order can be reversed (see the top-of-file comment). Everything
// else (image/pan, vignette, context tag, cold-open/hard-cut opacity, audio)
// is identical to what SlidePanel already did, built from the same shared
// components.
// ---------------------------------------------------------------------------
function ContentSlide({
  slide,
  isFirst,
}: {
  slide: SlideConfig & { durationFrames: number; audioDurationFrames: number };
  isFirst: boolean;
}) {
  const frame = useCurrentFrame();
  const {
    durationFrames,
    audioDurationFrames,
    overlayText,
    image,
    captionLines,
    label,
    sourceWidth,
    sourceHeight,
    panFillMode,
    panDirection,
  } = slide;

  const opacity = isFirst
    ? 1
    : interpolate(frame, [0, HARD_CUT_FRAMES], [0, 1], {
        extrapolateLeft: 'clamp',
        extrapolateRight: 'clamp',
      });

  // Height of whatever caption cue CaptionOverlay is showing right now --
  // this is what GoldLowerThird needs to clear.
  const usableWidth = CAPTION_MAX_WIDTH - CAPTION_H_PADDING * 2;
  const activeCaptionHeight = captionLines
    ? captionBlockHeight(
        estimateWrappedLineCount(getActiveCaptionLine(captionLines, frame, audioDurationFrames), usableWidth, CAPTION_FONT_SIZE),
        CAPTION_FONT_SIZE,
      )
    : 0;

  // HeadlineBox's box bottom edge normally sits at
  // (safeZoneBottomY - BOTTOM_SAFE_BUFFER) + bottomOffset. CaptionOverlay's
  // box (hugging the same safe-zone line, per CAPTION_HUG_BOTTOM_TOP above)
  // has its own top edge at (safeZoneBottomY - BOTTOM_SAFE_BUFFER) -
  // activeCaptionHeight. Setting HeadlineBox's bottom edge to (caption's top
  // edge - gap) and solving for bottomOffset cancels the shared
  // (safeZoneBottomY - BOTTOM_SAFE_BUFFER) term entirely:
  //   bottomOffset = -(activeCaptionHeight + HEADLINE_CAPTION_GAP)
  // This cancellation holds for ANY safeZoneBottomY value, as long as
  // HeadlineBox and CaptionOverlay below are both given the SAME one --
  // which is why ANTIETAM_SAFE_ZONE_BOTTOM_Y only needs to be passed to
  // the two components below, with no change to this formula.
  const headlineBottomOffset = -(activeCaptionHeight + HEADLINE_CAPTION_GAP);

  return (
    <AbsoluteFill style={{ backgroundColor: '#000', opacity }}>
      {image && (
        <>
          <KenBurnsImage
            image={image}
            frame={frame}
            durationFrames={durationFrames}
            sourceWidth={sourceWidth}
            sourceHeight={sourceHeight}
            panFillMode={panFillMode}
            panDirection={panDirection}
          />
          <Vignette />
        </>
      )}

      {label && <ContextTag text={label} position="top-left" />}

      {overlayText && (
        <HeadlineBox
          text={overlayText}
          frame={frame}
          bottomOffset={headlineBottomOffset}
          safeZoneBottomY={ANTIETAM_SAFE_ZONE_BOTTOM_Y}
        />
      )}

      {captionLines && (
        <CaptionOverlay
          lines={captionLines}
          audioDurationFrames={audioDurationFrames}
          top={CAPTION_HUG_BOTTOM_TOP}
          safeZoneBottomY={ANTIETAM_SAFE_ZONE_BOTTOM_Y}
        />
      )}

      <Audio src={staticFile(slide.audio)} />
    </AbsoluteFill>
  );
}

// ---------------------------------------------------------------------------
// End card. Trigger word SHARPSBURG, subline points at the dedicated 5-Fact
// Antietam PDF (not the standing BLUEGRAY CTA_CONFIG subline, which points
// at the generic Civil War PDF) -- same one-off-subline pattern as
